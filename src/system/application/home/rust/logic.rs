/// あいさつの文を作る
pub fn greeting(name: &str) -> String {
    format!("こんにちは、{name} さん！（ホームの Rust より）")
}

/// 割り算（0 で割ろうとしたら Err）
pub fn divide(a: f64, b: f64) -> Result<f64, String> {
    if b == 0.0 {
        return Err("0 では割れません".into());
    }
    Ok(a / b)
}
