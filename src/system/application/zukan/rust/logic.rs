/// 名前からレア度（1〜5）を決める
/// 名前の文字の番号（文字コード）を全部たして、5 で割ったあまり + 1 にする
/// → 同じ名前なら、いつも同じレア度になる
pub fn rarity(name: &str) -> u8 {
    let total: u32 = name.chars().map(|c| c as u32).sum();   // 1 文字ずつ番号にして、たす
    (total % 5) as u8 + 1                                      // 0〜4 → 1〜5
}
