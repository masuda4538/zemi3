export function sampleRoom() {
  const list = ROOM_TALK.map(([days, time, who, text, quiz, pin], i) => ({
    id: `s-room-${i + 1}`,
    from: who === "m" ? "me" : who === "s" ? "system" : "friend",
    ...(who !== "m" && who !== "s" ? { by: who } : {}),
    type: quiz ? "quiz" : who === "s" ? "system" : "text", text, ...(quiz ? { quiz } : {}), at: when(days, time), pin: !!pin,
  }));
  const pins = list.filter((x) => x.pin).map((x) => x.id).reverse();
  list.forEach((x) => { delete x.pin; });
  const got = list.filter((x) => x.from === "friend");
  const mark = new Date(new Date(got[got.length - 2].at).getTime() - 1000).toISOString();   // さいごの 2 こ は まだ見ていない
  return { room: { ...ROOM, members: [...ROOM.members] }, list, mark, pins };
}

