/** さいしょから「まだ見ていない」にする 相手のメッセージの数（さいごから数える） */
const UNREAD = { taro: 2, hanako: 1, jiro: 2, yuki: 0 };

/** 何日前・時刻 → 日時（文字）。今日は「何分前」 */
function when(days, time) {
  if (days === 0) return new Date(Date.now() - time * 60 * 1000).toISOString();
  const d = new Date();
  d.setDate(d.getDate() - days);
  const [h, m] = time.split(":").map(Number);
  d.setHours(h, m, 0, 0);
  return d.toISOString();
}

export function sampleChats() {
  const chats = {}, marks = {}, pins = {};
  for (const [friendId, rows] of Object.entries(TALKS)) {
    const list = rows.map(([days, time, who, text, quiz, pin], i) => ({
      id: `s-${friendId}-${i + 1}`, from: who === "m" ? "me" : "friend", type: quiz ? "quiz" : "text", text,
      ...(quiz ? { quiz } : {}), at: when(days, time), pin: !!pin,
    }));
    // ピン止め（あとのものほど 前）
    pins[friendId] = list.filter((x) => x.pin).map((x) => x.id).reverse();
    list.forEach((x) => { delete x.pin; });
    chats[friendId] = list;
    // どこまで見たか：さいごの UNREAD こ の 相手のメッセージより 1 秒前
    const got = list.filter((x) => x.from === "friend");
    const n = UNREAD[friendId] ?? 0;
    marks[friendId] = n > 0 && got.length >= n
      ? new Date(new Date(got[got.length - n].at).getTime() - 1000).toISOString()
      : new Date().toISOString();
  }
  return { chats, marks, pins };
}

